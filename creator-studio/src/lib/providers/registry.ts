const ADAPTERS: Record<string, ProviderAdapters> = {
  builtin: builtinAdapters,
  anthropic: anthropicAdapters,
  openai: openaiAdapters,
  gemini: geminiAdapters,
  runway: runwayAdapters,
  kling: klingAdapters,
  seedance: seedanceAdapters,
  elevenlabs: elevenlabsAdapters,
};

export function getProvider(id: string): ProviderInfo | undefined {
  return PROVIDERS.find((p) => p.id === id);
}

export function getAdapters(id: string): ProviderAdapters {
  const p = getProvider(id);
  if (!p || p.status === 'discontinued' || p.status === 'unavailable' || p.status === 'manual') return {};
  return ADAPTERS[id] ?? {};
}

export function providersFor(cap: Capability): ProviderInfo[] {
  return PROVIDERS.filter((p) => p.capabilities.includes(cap));
}

export function defaultModel(providerId: string, cap: Capability): ModelInfo | undefined {
  const models = getProvider(providerId)?.models.filter((m) => m.capability === cap) ?? [];
  return models.find((m) => m.default) ?? models[0];
}

export function findModel(providerId: string, modelId: string): ModelInfo | undefined {
  return getProvider(providerId)?.models.find((m) => m.id === modelId);
}

/** Estimated USD cost for a unit of work; null when unknown (custom model or no estimate). */
export function estimateCost(providerId: string, modelId: string, qty: { images?: number; seconds?: number; chars?: number; inputTokens?: number }): number | null {
  const m = findModel(providerId, modelId);
  if (!m?.cost) return providerId === 'builtin' ? 0 : null;
  const c = m.cost;
  switch (c.unit) {
    case 'image': return (qty.images ?? 1) * c.usd;
    case 'second': return (qty.seconds ?? 0) * c.usd;
    case 'minute': return ((qty.seconds ?? 0) / 60) * c.usd;
    case '1k-chars': return ((qty.chars ?? 0) / 1000) * c.usd;
    case '1m-input-tokens': return ((qty.inputTokens ?? 0) / 1_000_000) * c.usd;
    case 'request': return c.usd;
  }
}
